-- QUAN LY BAN HANG - SQL SERVER
-- Giu ten 5 bang, cac truong, PK/FK theo bao cao thiet ke.
-- Dieu chinh VARCHAR -> NVARCHAR cho cac truong tieng Viet de nhap Unicode.
-- Chay file nay trong SSMS truoc khi khoi dong ung dung Java.
IF DB_ID(N'QuanLyBanHang') IS NULL
    EXEC(N'CREATE DATABASE [QuanLyBanHang]');
GO
USE [QuanLyBanHang];
GO
IF OBJECT_ID(N'dbo.NHANVIEN', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.NHANVIEN (
        MANV CHAR(4) NOT NULL CONSTRAINT PK_NHANVIEN PRIMARY KEY,
        HOTEN NVARCHAR(40) NOT NULL,
        SODT VARCHAR(20) NULL,
        NGVL DATETIME NULL
    );
END;
GO
IF OBJECT_ID(N'dbo.SANPHAM', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.SANPHAM (
        MASP CHAR(4) NOT NULL CONSTRAINT PK_SANPHAM PRIMARY KEY,
        TENSP NVARCHAR(40) NOT NULL,
        DVT NVARCHAR(20) NULL,
        NUOCSX NVARCHAR(40) NULL,
        GIA MONEY NOT NULL CONSTRAINT CK_SANPHAM_GIA CHECK (GIA >= 0)
    );
END;
GO
IF OBJECT_ID(N'dbo.KHACHHANG', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.KHACHHANG (
        MAKH CHAR(4) NOT NULL CONSTRAINT PK_KHACHHANG PRIMARY KEY,
        HOTEN NVARCHAR(40) NOT NULL,
        DCHI NVARCHAR(50) NULL,
        SODT VARCHAR(20) NULL,
        NGSINH DATETIME NULL,
        NGDK DATETIME NULL,
        DOANHSO MONEY NOT NULL CONSTRAINT DF_KHACHHANG_DOANHSO DEFAULT (0),
        CONSTRAINT CK_KHACHHANG_DOANHSO CHECK (DOANHSO >= 0)
    );
END;
GO
IF OBJECT_ID(N'dbo.HOADON', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.HOADON (
        SOHD INT NOT NULL CONSTRAINT PK_HOADON PRIMARY KEY,
        NGHD SMALLDATETIME NOT NULL,
        MAKH CHAR(4) NULL,
        MANV CHAR(4) NOT NULL,
        TRIGIA MONEY NOT NULL CONSTRAINT DF_HOADON_TRIGIA DEFAULT (0),
        CONSTRAINT CK_HOADON_TRIGIA CHECK (TRIGIA >= 0),
        CONSTRAINT FK_HOADON_KHACHHANG FOREIGN KEY (MAKH) REFERENCES dbo.KHACHHANG(MAKH),
        CONSTRAINT FK_HOADON_NHANVIEN FOREIGN KEY (MANV) REFERENCES dbo.NHANVIEN(MANV)
    );
END;
GO
IF OBJECT_ID(N'dbo.CTHD', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CTHD (
        SOHD INT NOT NULL,
        MASP CHAR(4) NOT NULL,
        SL INT NOT NULL CONSTRAINT CK_CTHD_SL CHECK (SL > 0),
        CONSTRAINT PK_CTHD PRIMARY KEY (SOHD, MASP),
        CONSTRAINT FK_CTHD_HOADON FOREIGN KEY (SOHD) REFERENCES dbo.HOADON(SOHD),
        CONSTRAINT FK_CTHD_SANPHAM FOREIGN KEY (MASP) REFERENCES dbo.SANPHAM(MASP)
    );
END;
GO
SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_TYPE = 'BASE TABLE' AND TABLE_SCHEMA = 'dbo'
ORDER BY TABLE_NAME;
GO
